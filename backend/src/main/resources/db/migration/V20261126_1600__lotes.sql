create table stock_lot (
    id          bigint generated by default as identity primary key,
    product_id  bigint      not null references product (id),
    quantity    integer     not null check (quantity >= 0),
    expires_on  date,
    received_at timestamptz not null default now()
);

create index stock_lot_product on stock_lot (product_id) where quantity > 0;

-- El stock que ya existía pasa a un lote sin vencimiento.
insert into stock_lot (product_id, quantity)
select id, stock from product where stock > 0;
